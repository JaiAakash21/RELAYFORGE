#!/usr/bin/env bash
#
# Generates a .env with real secrets.
#
# Run once before `docker compose up`. The application refuses to start on a
# placeholder key, which is deliberate: a system that appears to work while
# encrypting every tenant's secrets under a value copied from an example file
# is worse than one that stops.
#
#   ./infra/scripts/bootstrap.sh
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="$REPO_ROOT/.env"

if [[ -f "$ENV_FILE" ]]; then
  echo "A .env already exists at $ENV_FILE"
  echo "Delete it yourself if you want fresh secrets — this script will not"
  echo "overwrite it, because doing so would make every stored webhook secret"
  echo "and every issued token undecryptable."
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate secrets." >&2
  exit 1
fi

echo "Generating secrets…"
# 64 bytes for HS512, 32 for AES-256. Both are checked at startup and the
# application refuses anything shorter.
JWT_SECRET="$(openssl rand -base64 64 | tr -d '\n')"
ENCRYPTION_KEY="$(openssl rand -base64 32 | tr -d '\n')"
POSTGRES_PASSWORD="$(openssl rand -hex 24)"
GRAFANA_PASSWORD="$(openssl rand -hex 16)"
DEMO_PASSWORD="$(openssl rand -hex 12)"

cat > "$ENV_FILE" <<EOF
# Generated by infra/scripts/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# This file is git-ignored. Do not commit it.
#
# Regenerating RELAYFORGE_ENCRYPTION_KEY makes every stored webhook secret
# unreadable, and regenerating RELAYFORGE_JWT_SECRET invalidates every issued
# token. Back this file up if the data matters.

POSTGRES_DB=relayforge
POSTGRES_USER=relayforge
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_PORT=5432

REDIS_PORT=6379
KAFKA_EXTERNAL_PORT=29092

RELAYFORGE_JWT_SECRET=$JWT_SECRET
RELAYFORGE_ENCRYPTION_KEY=$ENCRYPTION_KEY
RELAYFORGE_JWT_ACCESS_TTL=PT15M
RELAYFORGE_JWT_REFRESH_TTL=P7D

# dev: http allowed, and the webhook-simulator hostname is exempt from the
# private-address block. Never use dev outside local development.
RELAYFORGE_EGRESS_PROFILE=dev
RELAYFORGE_EGRESS_DEV_ALLOWLIST=webhook-simulator,localhost,host.docker.internal
RELAYFORGE_CORS_ORIGINS=http://localhost:3000

RELAYFORGE_DELIVERY_CONCURRENCY=4
RELAYFORGE_TRACING_SAMPLE_RATE=1.0

API_PORT=8080
FRONTEND_PORT=3000
PROMETHEUS_PORT=9090
GRAFANA_PORT=3001

GRAFANA_ADMIN_USER=admin
GRAFANA_ADMIN_PASSWORD=$GRAFANA_PASSWORD

NEXT_PUBLIC_SITE_URL=http://localhost:3000
NEXT_PUBLIC_GITHUB_URL=https://github.com/JaiAakash21/RELAYFORGE

# Seeds a demo account on first start. Off by default: an account with a known
# password is a backdoor, and it must never be created by accident.
RELAYFORGE_DEMO_SEED_ENABLED=false
RELAYFORGE_DEMO_EMAIL=demo@relayforge.dev
RELAYFORGE_DEMO_PASSWORD=$DEMO_PASSWORD
EOF

chmod 600 "$ENV_FILE"

cat <<EOF

Wrote $ENV_FILE (mode 600).

  Grafana admin password:  $GRAFANA_PASSWORD
  Demo account password:   $DEMO_PASSWORD  (only used if seeding is enabled)

Next:

  docker compose up --build

Then open:

  Dashboard   http://localhost:3000
  API docs    http://localhost:8080/swagger-ui.html
  Grafana     http://localhost:3001
  Prometheus  http://localhost:9090

To seed a demo account with an endpoint and an API key, set
RELAYFORGE_DEMO_SEED_ENABLED=true in .env and restart the api service. The key
is printed in its logs:  docker compose logs api | grep -A20 'demo environment'
EOF
